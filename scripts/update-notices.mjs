#!/usr/bin/env bun
// Refresh known upstream notices. This is not an exhaustive license audit.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const licenses = join(root, 'third_party/licenses');
const legalName = /^(license|licence|copying|notice|patents|copyright)/i;
// Conservative SPA/runtime/CSS/helper attribution, not whole-package shipment.
const frontend = [
  '@serenity-kit/opaque', '@sveltejs/kit', 'svelte', 'clsx', 'devalue',
  'esm-env', 'tailwindcss', 'vite',
];
const go = (...args) => execFileSync('go', args, { cwd: root, encoding: 'utf8' }).trim();
const bytes = (path) => readFileSync(path);
const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const outputs = new Map();
const entries = [];

function filesUnder(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesUnder(path) : entry.isFile() ? [path] : [];
  }).sort();
}

const existing = filesUnder(licenses);
function retain(name, version, source, category, scope, declared = '—') {
  const files = readdirSync(source, { withFileTypes: true })
    .filter((entry) => entry.isFile() && legalName.test(entry.name))
    .map((entry) => entry.name).sort();
  if (!files.length) throw new Error(`No upstream legal files for ${name}@${version}`);
  const retained = files.map((file) => {
    const data = bytes(join(source, file));
    const suffix = `${name}@${version}/${file}`;
    // Preserve historical files; reuse only matching exact-version legal text.
    const target = existing.find((path) => path.endsWith(`/${suffix}`) && bytes(path).equals(data))
      ?? join(licenses, category, suffix);
    outputs.set(target, data);
    return relative(root, target);
  });
  entries.push({ name, version, scope, declared, files: retained });
}

const requirements = JSON.parse(go('mod', 'edit', '-json'));
const cache = go('env', 'GOMODCACHE');
for (const module of requirements.Require.sort((a, b) => a.Path < b.Path ? -1 : a.Path > b.Path ? 1 : 0)) {
  const escaped = module.Path.replace(/[A-Z]/g, (letter) => `!${letter.toLowerCase()}`);
  retain(module.Path, module.Version, join(cache, `${escaped}@${module.Version}`),
    'current-go', 'Go requirement (not link inventory)');
}
const lock = readFileSync(join(root, 'web/bun.lock'), 'utf8');
for (const name of frontend) {
  const source = join(root, 'web/node_modules', name);
  const pkg = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8'));
  if (!lock.includes(`"${name}": ["${name}@${pkg.version}"`)) {
    throw new Error(`Installed ${name}@${pkg.version} does not match web/bun.lock`);
  }
  retain(name, pkg.version, source, 'frontend', 'SPA attribution set', pkg.license ?? 'unspecified');
}
const toolchain = go('env', 'GOVERSION');
if (toolchain !== `go${requirements.Go}`) {
  throw new Error('Use the Go toolchain pinned in go.mod to refresh notices');
}
retain('Go', toolchain, go('env', 'GOROOT'), 'toolchain', 'Go runtime/toolchain', 'BSD-3-Clause');

const inventory = [
  '# Current dependency notice inventory', '',
  'Generated by `bun scripts/update-notices.mjs` from `go.mod`, installed',
  'pinned module/package archives, and `web/bun.lock`. Use `--check` to detect drift.', '',
  'Go entries cover every direct/indirect requirement in go.mod, including tooling',
  'and platform-specific dependencies; they are **not** a list of modules linked',
  'into every binary. The frontend set conservatively attributes the SPA runtime,',
  'CSS, and bundler helpers, not every build tool or the full contents of packages.',
  'Only package/module-root legal files are collected automatically. Nested,',
  'generated, vendored, and native dependency notices still need review under #26.', '',
  "Serenity's historical embedded Rust/WASM dependency closure remains unresolved.",
  'This inventory does not close #25/#26 or certify distribution compliance.', '',
  'Older retained versions elsewhere in `third_party/licenses/` are historical;',
  'the table below identifies the currently selected versions.', '',
  '| Component | Version | Scope | Declared package license | Retained files |',
  '| --- | --- | --- | --- | --- |',
];
for (const entry of entries) {
  const links = entry.files.map((file) => `[${file.split('/').at(-1)}](${file.replace(/^third_party\//, '')})`).join(', ');
  inventory.push(`| \`${entry.name}\` | \`${entry.version}\` | ${entry.scope} | ${entry.declared} | ${links} |`);
}
outputs.set(join(root, 'third_party/DEPENDENCIES.md'), Buffer.from(inventory.join('\n') + '\n'));

const publicNotice = [
  'Deploy Manager — third-party notices', '',
  'These notices accompany the currently selected Go and browser components.',
  "They do not relicense third-party code under the application's license.",
  'This is a partial inventory, not complete distribution clearance: the exact',
  'historical Rust dependency/license closure inside Serenity OPAQUE 1.1.0 WASM',
  'is unavailable. Nested/generated/native notices need further review (#26).',
  'The published browser fix is tracked separately in #25.', '',
  'Go requirements include tooling/platform-specific code that may not be linked.',
  'Frontend attribution is conservative; entire packages need not be shipped.', '',
];
const included = new Set();
for (const entry of entries) {
  publicNotice.push('='.repeat(72), `${entry.name} ${entry.version}`, `Scope: ${entry.scope}`, '');
  for (const file of entry.files) {
    const data = outputs.get(join(root, file));
    const digest = sha256(data);
    if (included.has(digest)) {
      publicNotice.push(`${file.split('/').at(-1)}: identical legal text reproduced above.`, '');
    } else {
      included.add(digest);
      publicNotice.push(`--- ${file} ---`, data.toString('utf8'), '');
    }
  }
}
outputs.set(join(root, 'web/static/third-party-notices.txt'), Buffer.from(publicNotice.join('\n') + '\n'));

const args = process.argv.slice(2);
if (args.some((arg) => arg !== '--check')) throw new Error('Usage: bun scripts/update-notices.mjs [--check]');
const changed = [...outputs].filter(([path, data]) => !existsSync(path) || !bytes(path).equals(data));
if (args.includes('--check')) {
  for (const [path] of changed) console.error(`Out of date: ${relative(root, path)}`);
  process.exitCode = changed.length ? 1 : 0;
} else {
  for (const [path, data] of changed) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, data);
  }
  console.log(`Updated ${changed.length} files; checked ${outputs.size} notice files.`);
}
